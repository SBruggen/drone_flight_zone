#!/usr/bin/env python3
"""Convert DJI Waypoint Mission KMZ files to QGIS-ready GeoPackage layers.

The source KMZ files are opened read-only and are never modified.  The parser is
aimed at DJI WPML files (``wpmz/waylines.wpml``), including files generated by
Aerial 3D.
"""

from __future__ import annotations

import argparse
import math
import re
import shutil
import subprocess
import sys
import zipfile
from dataclasses import dataclass
from pathlib import Path
from statistics import median
from typing import Iterable
from xml.etree import ElementTree as ET

import geopandas as gpd
from pyproj import CRS, Geod, Transformer
from shapely.geometry import LineString, MultiPoint, MultiPolygon, Point, Polygon
from shapely.ops import polygonize, unary_union
from shapely.strtree import STRtree

KML = "http://www.opengis.net/kml/2.2"
WPML = "http://www.uav.com/wpmz/1.0.2"
NS = {"kml": KML, "wpml": WPML}
WGS84 = CRS.from_epsg(4326)
GEOD = Geod(ellps="WGS84")


@dataclass
class Waypoint:
    zone: str
    mission: str
    flight_id: str
    source_file: str
    sequence: int
    source_index: int
    lon: float
    lat: float
    height_m: float | None
    speed_ms: float | None
    heading_deg: float | None
    heading_mode: str | None
    poi_lon: float | None
    poi_lat: float | None
    poi_alt_m: float | None
    gimbal_pitch_deg: float | None
    take_photo: bool


def text(element: ET.Element, path: str) -> str | None:
    node = element.find(path, NS)
    if node is None or node.text is None:
        return None
    value = node.text.strip()
    return value or None


def number(value: str | None) -> float | None:
    try:
        return float(value) if value is not None else None
    except ValueError:
        return None


def safe_name(value: str) -> str:
    return re.sub(r"[^0-9A-Za-z_-]+", "_", value).strip("_") or "mission"


def find_wpml_member(archive: zipfile.ZipFile) -> str:
    candidates = [n for n in archive.namelist() if n.lower().endswith("waylines.wpml")]
    if not candidates:
        candidates = [n for n in archive.namelist() if n.lower().endswith(".wpml")]
    if not candidates:
        raise ValueError("geen waylines.wpml gevonden")
    return candidates[0]


def parse_poi(value: str | None) -> tuple[float | None, float | None, float | None]:
    """DJI WPML stores POI as latitude,longitude,altitude (unlike KML)."""
    if not value:
        return None, None, None
    try:
        parts = [float(v.strip()) for v in value.split(",")]
    except ValueError:
        return None, None, None
    if len(parts) < 2:
        return None, None, None
    return parts[1], parts[0], parts[2] if len(parts) > 2 else None


def parse_kmz(path: Path) -> list[Waypoint]:
    with zipfile.ZipFile(path, "r") as archive:
        root = ET.fromstring(archive.read(find_wpml_member(archive)))
    # DJI enterprise exports use dji.com; original Aerial 3D files use uav.com.
    for node in root.iter():
        if node.tag.startswith("{http://www.dji.com/wpmz/1.0.2}"):
            node.tag = node.tag.replace("http://www.dji.com/wpmz/1.0.2", WPML, 1)

    zone = safe_name(path.parent.name)
    mission = safe_name(path.stem)
    flight_id = f"{zone}__{mission}"
    result: list[Waypoint] = []
    # Gimbal actions are state changes: Aerial 3D commonly sets pitch only at
    # the first waypoint, after which that angle remains active.
    active_pitch: float | None = None
    for sequence, placemark in enumerate(root.findall(".//kml:Placemark", NS), start=1):
        coordinates = text(placemark, "kml:Point/kml:coordinates")
        if not coordinates:
            continue
        values = [float(v.strip()) for v in coordinates.split(",")]
        lon, lat = values[:2]
        source_index = int(number(text(placemark, "wpml:index")) or sequence - 1)

        take_photo = False
        for action in placemark.findall(".//wpml:action", NS):
            function = text(action, "wpml:actionActuatorFunc")
            if function == "takePhoto":
                take_photo = True
            elif function == "gimbalRotate":
                pitch = number(text(action, ".//wpml:gimbalPitchRotateAngle"))
                if pitch is not None:
                    active_pitch = pitch

        poi_lon, poi_lat, poi_alt = parse_poi(
            text(placemark, "wpml:waypointHeadingParam/wpml:waypointPoiPoint")
        )
        heading = number(text(placemark, "wpml:waypointHeadingParam/wpml:waypointHeadingAngle"))
        # A direct geodetic bearing is more robust for target-oriented missions.
        if poi_lon is not None and poi_lat is not None:
            heading = GEOD.inv(lon, lat, poi_lon, poi_lat)[0] % 360.0

        result.append(
            Waypoint(
                zone=zone,
                mission=mission,
                flight_id=flight_id,
                source_file=str(path),
                sequence=sequence,
                source_index=source_index,
                lon=lon,
                lat=lat,
                height_m=number(text(placemark, "wpml:executeHeight")),
                speed_ms=number(text(placemark, "wpml:waypointSpeed")),
                heading_deg=heading,
                heading_mode=text(placemark, "wpml:waypointHeadingParam/wpml:waypointHeadingMode"),
                poi_lon=poi_lon,
                poi_lat=poi_lat,
                poi_alt_m=poi_alt,
                gimbal_pitch_deg=active_pitch,
                take_photo=take_photo,
            )
        )
    if not result:
        raise ValueError("geen waypoint-Placemarks gevonden")
    return result


def projected_xy(transformer: Transformer, lon: float, lat: float) -> tuple[float, float]:
    x, y = transformer.transform(lon, lat)
    return float(x), float(y)


def camera_footprint(
    x: float,
    y: float,
    height: float,
    bearing_deg: float,
    pitch_deg: float,
    diagonal_fov_deg: float,
    aspect_ratio: float,
) -> Polygon | None:
    """Intersect four camera-frustum corner rays with a flat ground plane."""
    if height <= 0 or not (-90 <= pitch_deg < 0):
        return None
    depression = math.radians(-pitch_deg)
    bearing = math.radians(bearing_deg)
    half_diagonal = math.radians(diagonal_fov_deg / 2)
    diagonal_factor = math.sqrt(aspect_ratio * aspect_ratio + 1.0)
    half_h = math.atan(math.tan(half_diagonal) * aspect_ratio / diagonal_factor)
    half_v = math.atan(math.tan(half_diagonal) / diagonal_factor)

    # Local axes: x=east, y=north, z=up.
    forward = [math.cos(depression) * math.sin(bearing),
               math.cos(depression) * math.cos(bearing), -math.sin(depression)]
    right = [math.cos(bearing), -math.sin(bearing), 0.0]
    up = [math.sin(depression) * math.sin(bearing),
          math.sin(depression) * math.cos(bearing), math.cos(depression)]
    corners: list[tuple[float, float]] = []
    for horizontal, vertical in ((-1, 1), (1, 1), (1, -1), (-1, -1)):
        ray = [
            forward[i]
            + horizontal * math.tan(half_h) * right[i]
            + vertical * math.tan(half_v) * up[i]
            for i in range(3)
        ]
        if ray[2] >= -1e-9:  # ray does not meet the ground in front of the camera
            return None
        scale = -height / ray[2]
        corners.append((x + scale * ray[0], y + scale * ray[1]))
    polygon = Polygon(corners)
    return polygon if polygon.is_valid and not polygon.is_empty else polygon.buffer(0)


def records_gdf(records: list[dict], geometries: list, crs: CRS) -> gpd.GeoDataFrame:
    return gpd.GeoDataFrame(records, geometry=geometries, crs=crs)


def overlap_zones(
    footprints: gpd.GeoDataFrame, crs: CRS, minimum_overlap: int = 2
) -> gpd.GeoDataFrame:
    """Create one global planar subdivision labelled with the image count.

    Polygonizing all footprint boundaries produces non-overlapping faces.  A
    representative point of every face is then queried against the original
    footprints.  Faces with the same count are dissolved afterwards.  The
    subdivision is deliberately global, not per mission: otherwise overlap
    polygons belonging to different missions would still overlap each other.
    """
    records: list[dict] = []
    geometries: list = []
    source = list(footprints.geometry)
    tree = STRtree(source)
    boundary_network = unary_union([geometry.boundary for geometry in source])
    faces = list(polygonize(boundary_network))
    by_count: dict[int, list[Polygon]] = {}
    for face in faces:
        sample = face.representative_point()
        count = len(tree.query(sample, predicate="intersects"))
        if count >= minimum_overlap:
            by_count.setdefault(count, []).append(face)

    for count, matching_faces in sorted(by_count.items()):
        dissolved = unary_union(matching_faces)
        multipart = dissolved if dissolved.geom_type == "MultiPolygon" else MultiPolygon([dissolved])
        records.append({
            "overlap_aantal": count,
            "deelgebieden": len(multipart.geoms),
            "oppervlakte_m2": multipart.area,
            "model": "vlak terrein (theoretisch)",
        })
        geometries.append(multipart)
    return records_gdf(records, geometries, crs)


def build_layers(
    waypoints: list[Waypoint], output_crs: CRS, diagonal_fov: float, aspect_ratio: float,
    create_vector_overlap: bool = True, assume_photo_at_waypoints: bool = False,
    footprint_plane: str = "ground",
    mission_buffer_m: float = 5.0,
) -> dict[str, gpd.GeoDataFrame]:
    if not math.isfinite(mission_buffer_m) or mission_buffer_m <= 0:
        raise ValueError("missiebuffer moet een eindig getal groter dan nul zijn")
    if (not output_crs.is_projected or len(output_crs.axis_info) < 2
            or any(axis.unit_conversion_factor != 1 for axis in output_crs.axis_info[:2])):
        raise ValueError("uitvoer-CRS moet een geprojecteerd CRS in meter zijn")
    transformer = Transformer.from_crs(WGS84, output_crs, always_xy=True)
    by_mission: dict[str, list[Waypoint]] = {}
    for waypoint in waypoints:
        by_mission.setdefault(waypoint.flight_id, []).append(waypoint)

    wp_records, wp_geoms = [], []
    direction_records, direction_geoms = [], []
    footprint_records, footprint_geoms = [], []
    orbit_groups: dict[tuple[str, float, float], list[tuple[Waypoint, Point]]] = {}

    for wp in waypoints:
        point = Point(projected_xy(transformer, wp.lon, wp.lat))
        label = f"{wp.mission}-{wp.sequence:03d}"
        wp_records.append({
            "zone": wp.zone, "mission": wp.mission, "vlucht_id": wp.flight_id,
            "wp_nr": wp.sequence, "bron_index": wp.source_index,
            "label": label, "hoogte_m": wp.height_m, "snelheid_ms": wp.speed_ms,
            "koers_deg": wp.heading_deg, "koersmodus": wp.heading_mode,
            "gimbal_deg": wp.gimbal_pitch_deg, "neemt_foto": int(wp.take_photo),
            "poi_lon": wp.poi_lon, "poi_lat": wp.poi_lat,
            "bronbestand": wp.source_file,
        })
        wp_geoms.append(point)

        if wp.poi_lon is not None and wp.poi_lat is not None:
            poi = Point(projected_xy(transformer, wp.poi_lon, wp.poi_lat))
            direction_records.append({
                "zone": wp.zone, "mission": wp.mission, "vlucht_id": wp.flight_id,
                "wp_nr": wp.sequence, "label": label,
                "koers_deg": wp.heading_deg, "gimbal_deg": wp.gimbal_pitch_deg,
                "afstand_m": point.distance(poi),
            })
            direction_geoms.append(LineString([point, poi]))
            key = (wp.flight_id, round(wp.poi_lon, 6), round(wp.poi_lat, 6))
            orbit_groups.setdefault(key, []).append((wp, point))

        use_as_photo = wp.take_photo or assume_photo_at_waypoints
        if (use_as_photo and wp.height_m is not None and wp.heading_deg is not None
                and wp.gimbal_pitch_deg is not None):
            plane_height = (wp.poi_alt_m or 0.0) if footprint_plane == "aim" else 0.0
            effective_height = wp.height_m - plane_height
            footprint = camera_footprint(
                point.x, point.y, effective_height, wp.heading_deg, wp.gimbal_pitch_deg,
                diagonal_fov, aspect_ratio,
            )
            if footprint is not None:
                footprint_records.append({
                    "zone": wp.zone, "mission": wp.mission, "vlucht_id": wp.flight_id,
                    "wp_nr": wp.sequence, "label": label,
                    "hoogte_m": wp.height_m, "koers_deg": wp.heading_deg,
                    "gimbal_deg": wp.gimbal_pitch_deg, "dfov_deg": diagonal_fov,
                    "aspect": aspect_ratio, "model": "vlak terrein (benadering)",
                    "projectievlak_m": plane_height,
                    "foto_basis": "WPML takePhoto" if wp.take_photo else "aangenomen op waypoint",
                })
                footprint_geoms.append(footprint)

    layers: dict[str, gpd.GeoDataFrame] = {
        "waypoints": records_gdf(wp_records, wp_geoms, output_crs),
        "kijkrichtingen": records_gdf(direction_records, direction_geoms, output_crs),
    }

    path_records, path_geoms = [], []
    mission_records, mission_geoms = [], []
    for flight_id, items in by_mission.items():
        ordered = sorted(items, key=lambda item: item.sequence)
        coordinates = [projected_xy(transformer, w.lon, w.lat) for w in ordered]
        # The hull encloses the waypoints, rather than following the flight order.
        # A positive buffer also gives single-point and collinear missions a polygon.
        polygon = MultiPoint(coordinates).convex_hull.buffer(mission_buffer_m)
        mission_records.append({
            "zone": ordered[0].zone, "mission": ordered[0].mission,
            "vlucht_id": flight_id, "waypoints": len(ordered),
            "buffer_m": mission_buffer_m, "oppervlakte_m2": polygon.area,
            "model": "convex hull waypoints + buffer",
            "bronbestand": ordered[0].source_file,
        })
        mission_geoms.append(polygon)
        if len(coordinates) < 2:
            continue
        geometry = LineString(coordinates)
        path_records.append({
            "zone": ordered[0].zone, "mission": ordered[0].mission,
            "vlucht_id": flight_id, "waypoints": len(ordered),
            "lengte_m": geometry.length, "bronbestand": ordered[0].source_file,
        })
        path_geoms.append(geometry)
    layers["vliegroutes"] = records_gdf(path_records, path_geoms, output_crs)
    layers["missiepolygonen"] = records_gdf(mission_records, mission_geoms, output_crs)

    centre_records, centre_geoms, circle_records, circle_geoms = [], [], [], []
    orbit_counter: dict[str, int] = {}
    for (flight_id, poi_lon, poi_lat), members in sorted(orbit_groups.items()):
        orbit_counter[flight_id] = orbit_counter.get(flight_id, 0) + 1
        orbit_nr = orbit_counter[flight_id]
        centre = Point(projected_xy(transformer, poi_lon, poi_lat))
        radii = [point.distance(centre) for _, point in members]
        radius = median(radii)
        first = members[0][0]
        orbit_id = f"{flight_id}-C{orbit_nr:03d}"
        common = {
            "zone": first.zone, "mission": first.mission, "vlucht_id": flight_id,
            "cirkel_id": orbit_id, "straal_m": radius,
            "wp_aantal": len(members), "eerste_wp": min(w.sequence for w, _ in members),
            "laatste_wp": max(w.sequence for w, _ in members),
        }
        centre_records.append(common.copy())
        centre_geoms.append(centre)
        circle_records.append(common.copy())
        circle_geoms.append(centre.buffer(radius, resolution=72).boundary)
    layers["cirkelcentra"] = records_gdf(centre_records, centre_geoms, output_crs)
    layers["vliegcirkels"] = records_gdf(circle_records, circle_geoms, output_crs)

    if footprint_records:
        footprint_layer = records_gdf(footprint_records, footprint_geoms, output_crs)
        layers["foto_footprints"] = footprint_layer
        if create_vector_overlap:
            layers["beeld_overlap"] = overlap_zones(footprint_layer, output_crs)
    return layers


def write_layers(layers: dict[str, gpd.GeoDataFrame], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        output.unlink()
    for layer_name, frame in layers.items():
        if not frame.empty:
            frame.to_file(output, layer=layer_name, driver="GPKG", index=False)


def write_overlap_raster(
    gpkg: Path, footprints: gpd.GeoDataFrame, output: Path, resolution: float
) -> None:
    """Rasterize footprints with GDAL; every footprint adds one to a pixel."""
    executable = shutil.which("gdal_rasterize")
    if executable is None:
        raise RuntimeError(
            "gdal_rasterize is niet gevonden. Voer het script uit in de conda-gis omgeving."
        )
    if resolution <= 0:
        raise ValueError("rasterresolutie moet groter zijn dan nul")

    min_x, min_y, max_x, max_y = footprints.total_bounds
    # Align the extent to whole multiples of the requested pixel size.  Together
    # with -tap this makes independently generated rasters line up exactly.
    min_x = math.floor(min_x / resolution) * resolution
    min_y = math.floor(min_y / resolution) * resolution
    max_x = math.ceil(max_x / resolution) * resolution
    max_y = math.ceil(max_y / resolution) * resolution
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        output.unlink()
    command = [
        executable,
        "-l", "foto_footprints",
        "-burn", "1",
        "-add",
        "-init", "0",
        "-a_nodata", "0",
        "-ot", "UInt16",
        "-tr", str(resolution), str(resolution),
        "-tap",
        "-te", str(min_x), str(min_y), str(max_x), str(max_y),
        "-co", "TILED=YES",
        "-co", "COMPRESS=DEFLATE",
        "-co", "PREDICTOR=2",
        "-of", "GTiff",
        str(gpkg),
        str(output),
    ]
    subprocess.run(command, check=True)


def kmz_files(inputs: Iterable[str]) -> list[Path]:
    found: set[Path] = set()
    for raw in inputs:
        path = Path(raw)
        if path.is_dir():
            found.update(p.resolve() for p in path.rglob("*.kmz"))
        elif path.is_file() and path.suffix.lower() == ".kmz":
            found.add(path.resolve())
        else:
            print(f"Waarschuwing: overgeslagen (niet gevonden of geen KMZ): {path}", file=sys.stderr)
    return sorted(found)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", help="Een of meer KMZ-bestanden of mappen")
    parser.add_argument("-o", "--output", type=Path, default=Path("output/dronevluchten.gpkg"))
    parser.add_argument("--crs", default="EPSG:31370", help="Geprojecteerd uitvoer-CRS (standaard: EPSG:31370)")
    parser.add_argument(
        "--mission-buffer", type=float, default=5.0, metavar="METER",
        help="Buffer rond de buitenste omhullende van de missiewaypoints (standaard: 5 meter)",
    )
    parser.add_argument("--diagonal-fov", type=float, default=82.1,
                        help="Diagonale camerabeeldhoek in graden (standaard: 82.1)")
    parser.add_argument("--aspect-ratio", type=float, default=4 / 3,
                        help="Breedte/hoogte van het beeld (standaard: 4/3)")
    parser.add_argument(
        "--include-missions", nargs="+", type=int, metavar="NR",
        help="Verwerk alleen deze missienummers, bv. --include-missions 1 3 4 5",
    )
    parser.add_argument(
        "--no-vector-overlap", action="store_true",
        help="Sla de tragere exacte vectorlaag beeld_overlap over",
    )
    parser.add_argument(
        "--raster-output", type=Path,
        help="Schrijf daarnaast een GeoTIFF met het aantal beelden per pixel",
    )
    parser.add_argument(
        "--raster-resolution", type=float, default=1.0,
        help="Pixelgrootte in CRS-eenheden voor --raster-output (standaard: 1 meter)",
    )
    parser.add_argument(
        "--assume-photo-at-waypoints", action="store_true",
        help="Simuleer één foto per waypoint wanneer WPML geen takePhoto-acties bevat",
    )
    parser.add_argument(
        "--footprint-plane", choices=("ground", "aim"), default="ground",
        help="Projecteer footprints op maaiveld of op de WPML aim-hoogte (standaard: ground)",
    )
    args = parser.parse_args()

    try:
        crs = CRS.from_user_input(args.crs)
        if (not crs.is_projected or len(crs.axis_info) < 2
                or any(axis.unit_conversion_factor != 1 for axis in crs.axis_info[:2])):
            parser.error("--crs moet een geprojecteerd CRS in meter zijn, bv. EPSG:31370")
        if not math.isfinite(args.mission_buffer) or args.mission_buffer <= 0:
            parser.error("--mission-buffer moet een eindig getal groter dan nul zijn")
        if not 0 < args.diagonal_fov < 179:
            parser.error("--diagonal-fov moet tussen 0 en 179 liggen")
        if args.aspect_ratio <= 0:
            parser.error("--aspect-ratio moet groter zijn dan nul")
        files = kmz_files(args.inputs)
        if args.include_missions:
            selected = set(args.include_missions)
            files = [
                path for path in files
                if (match := re.fullmatch(r"Mission_(\d+)", path.stem, re.IGNORECASE))
                and int(match.group(1)) in selected
            ]
        if not files:
            parser.error("geen KMZ-bestanden gevonden voor de gekozen missies")

        all_waypoints: list[Waypoint] = []
        failures: list[str] = []
        for path in files:
            try:
                parsed = parse_kmz(path)
                all_waypoints.extend(parsed)
                print(f"Gelezen: {path.name} ({len(parsed)} waypoints)")
            except Exception as exc:  # continue so one damaged mission does not hide the others
                failures.append(f"{path}: {exc}")
        if not all_waypoints:
            raise RuntimeError("geen bruikbare waypoints gevonden\n" + "\n".join(failures))

        layers = build_layers(
            all_waypoints, crs, args.diagonal_fov, args.aspect_ratio,
            create_vector_overlap=not args.no_vector_overlap,
            assume_photo_at_waypoints=args.assume_photo_at_waypoints,
            footprint_plane=args.footprint_plane,
            mission_buffer_m=args.mission_buffer,
        )
        if args.raster_output and "foto_footprints" not in layers:
            raise RuntimeError(
                "geen takePhoto-acties gevonden; gebruik alleen voor een theoretische simulatie "
                "de optie --assume-photo-at-waypoints"
            )
        write_layers(layers, args.output.resolve())
        if args.raster_output:
            write_overlap_raster(
                args.output.resolve(), layers["foto_footprints"],
                args.raster_output.resolve(), args.raster_resolution,
            )
        print(f"\nGeoPackage: {args.output.resolve()}")
        for name, frame in layers.items():
            print(f"  {name}: {len(frame)} objecten")
        if args.raster_output:
            print(f"  overlapraster: {args.raster_output.resolve()}")
        if failures:
            print("\nWaarschuwingen:", file=sys.stderr)
            print("\n".join(failures), file=sys.stderr)
        return 0
    except Exception as exc:
        print(f"Fout: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
